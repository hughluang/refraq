export const MIRROR_STATUSES = ["waiting", "snapshotting", "catching_up", "ready", "stale", "rebuilding", "paused", "needs_attention", "disable_pending", "unknown", "disabled", "source_fault"] as const;
export type RecoveryAction = "retry" | "run_now" | "postpone" | "manual";
export type RecoveryRequest = {
  action: RecoveryAction;
  expected_history_epoch: string | number;
  expected_control_revision?: number;
  reason?: string;
};
export type ReadinessItem = {
  key: string;
  result: "pass" | "fail" | "unknown" | "not_applicable";
  expected: unknown;
  observed: unknown;
  observed_at: string | null;
  owner: string;
  action: string;
};
type StopAcknowledgment = {
  operation_id: string;
  source_operation_id: string;
  observed_at: string;
};
type MirrorControl = {
  control_revision: number;
  credential_revision: number | null;
  owner_epoch: number | null;
  runtime_instance_id: string | null;
  applied_revision: number | null;
  observed_at: string | null;
  stop_ack: StopAcknowledgment | null;
};
type MirrorOperation = {
  id: string;
  mirror_id: string;
  kind: "open" | "enable" | "disable" | "recovery";
  state: "pending" | "applied" | "superseded";
  control_revision: number;
  observed_evidence_refs: string[];
  fault_code: string | null;
  requested_at: string;
};
export type MirrorReference = { mirror_id: string; qualified_table: string };
export type JournalEvent = {
  id: string;
  category: "request" | "observation";
  kind: string;
  at: string;
  operation_id: string;
  control_revision: number;
  history_epoch: string | number | null;
  generation_id: string | null;
  outcome: string | null;
  outcome_at: string | null;
  related_operation_id: string | null;
};
export type JournalPage = { items: JournalEvent[]; next_cursor: string | null };
export type Mirror = {
  id: string;
  source_id: string;
  source_key: string;
  source_name: string;
  object_id: string;
  table_identity: string;
  qualified_table: string;
  enabled: boolean;
  status: (typeof MIRROR_STATUSES)[number];
  published_generation_id: string | null;
  capture_generation: string | null;
  history_epoch: string | number | null;
  retained_lower_bound: unknown;
  committed_upper_bound: unknown;
  control: MirrorControl;
  snapshot_slot_holder?: MirrorReference | null;
  publication_wait?: MirrorReference | null;
  progress: {
    stage: "scan" | "catching_up";
    generation_id: string;
    notification_offset: number;
    observed_at: string | null;
    scanned_bytes: number | null;
    byte_notification_offset: number | null;
    bytes_observed_at: string | null;
    scan_percent: number | null;
    scan_complete: boolean;
  } | null;
  profile: Record<string, unknown>;
  readiness: ReadinessItem[];
  fault: Record<string, unknown> | null;
  operations: MirrorOperation[];
  deletion_operation_id?: string | null;
};
export type MirrorDetail = Mirror & {
  storage_destination: string;
  source_size_bytes: number | null;
  estimated_rows: number | null;
  journal: JournalPage;
  latest_request: JournalEvent | null;
  open_request: JournalEvent | null;
  latest_observation: JournalEvent | null;
  continuity_check: JournalEvent | null;
  blocker: { cause: "permission" | "schema" | "continuity"; since: string; last_checked_at: string } | null;
  can_retry: boolean;
  allocated_generation_id: string | null;
  published_at: string | null;
};
export type PendingOperation = { operation_id: string; state: "pending" };
