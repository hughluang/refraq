def test_revert_failure_is_logged_and_original_error_kept(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    class _RevertFails(RecordingEntityTablePort):
        def revert_publish_table(
            self,
            schema: str,
            stem: str,
            *,
            archive_as: str | None,
            archive_attributes: list | None,
        ) -> None:
            del schema, stem, archive_as, archive_attributes
            raise RuntimeError("archive restore failed")

    bind_entity_table_port(_RevertFails())

    def _snapshot_fails(attributes: list) -> list:
        del attributes
        raise RuntimeError("snapshot write failed")

    monkeypatch.setattr(
        "backend.entity.align.snapshot_from_attributes", _snapshot_fails
    )
    entity = _create(client)
    version_id = entity["current_version"]["id"]
    published = client.post(
        f"/entities/{entity['id']}/versions/{version_id}/publish"
    )
    assert published.status_code == 201, published.text
    job = get_job_store().get(published.json()["job"]["id"])
    assert job is not None
    assert job.status == "failed"
    assert job.error_code == "JOB_EXECUTION_FAILED"
    assert "snapshot write failed" in (job.error_summary or "")
    assert "revert failed: archive restore failed" in job.log_body


