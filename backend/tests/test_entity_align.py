def test_drop_non_empty_table_fails_job(
    client: TestClient, port: RecordingEntityTablePort
) -> None:
    class _NonEmpty(RecordingEntityTablePort):
        def drop_table(self, schema: str, table: str) -> None:
            if table == "material__rfq_v1":
                raise EntityTableHasRows()
            super().drop_table(schema, table)

    occupied = _NonEmpty()
    occupied.statements = port.statements
    occupied._tables = port._tables
    bind_entity_table_port(occupied)
    entity = _create(client)
    v1 = entity["current_version"]["id"]
    _publish(client, entity)
    assert client.post(f"/entities/{entity['id']}/versions", json={}).status_code == 201
    current = client.get(f"/entities/{entity['id']}").json()["entity"]
    _publish(client, current)
    dropped = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert dropped.status_code == 201
    job = get_job_store().get(dropped.json()["job"]["id"])
    assert job is not None
    assert job.status == "failed"
    assert job.error_code == "ENTITY_TABLE_NOT_EMPTY"
    version = client.get(f"/entities/{entity['id']}/versions/{v1}")
    assert version.json()["version"]["alignment"]["table_present"] is True


def test_publish_and_drop_share_lock(client: TestClient) -> None:
    entity = _create(client)
    version_id = entity["current_version"]["id"]
    held = try_acquire_entity_table_lock(entity["id"])
    assert held is not None
    try:
        published = client.post(
            f"/entities/{entity['id']}/versions/{version_id}/publish"
        )
        assert published.status_code == 201
        job = get_job_store().get(published.json()["job"]["id"])
        assert job is not None
        assert job.status == "failed"
        assert job.error_code == "JOB_ALREADY_ACTIVE"
        version = client.get(f"/entities/{entity['id']}/versions/{version_id}")
        assert version.json()["version"]["publish_status"] == "unpublished"
    finally:
        held.release()
    assert find_inflight_entity_table_job(version_id) is None


