def test_inflight_publish_is_returned_not_duplicated(client: TestClient) -> None:
    entity = _create(client)
    version_id = entity["current_version"]["id"]
    queued = create_queued_job(
        kind=KIND_RECONCILE,
        input={"entity_version_id": version_id},
        created_by="user_admin",
        trigger_kind="user",
        trigger_ref="user_admin",
    )
    store = get_entity_store()
    version = store.get_version(version_id)
    assert version is not None
    store.save_version(
        replace(
            version,
            publish_status=PUBLISHING,
            latest_reconcile_job_id=queued.id,
            updated_at=utc_now(),
        )
    )
    again = client.post(f"/entities/{entity['id']}/versions/{version_id}/publish")
    assert again.status_code == 200
    assert again.json()["job"]["id"] == queued.id
    records, _ = get_job_store().list(kind=KIND_RECONCILE)
    assert len(records) == 1


def test_drop_current_refused_until_deprecated(
    client: TestClient, port: RecordingEntityTablePort
) -> None:
    entity = _create(client)
    v1 = entity["current_version"]["id"]
    _publish(client, entity)
    current_drop = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert current_drop.status_code == 422
    assert current_drop.json()["code"] == "ENTITY_VERSION_NOT_SUPERSEDED"

    opened = client.post(f"/entities/{entity['id']}/versions", json={})
    assert opened.status_code == 201
    present_delete = client.delete(f"/entities/{entity['id']}")
    assert present_delete.status_code == 409
    assert present_delete.json()["code"] == "ENTITY_ALREADY_PUBLISHED"

    still_live = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert still_live.status_code == 422
    assert still_live.json()["code"] == "ENTITY_VERSION_NOT_SUPERSEDED"

    assert client.post(f"/entities/{entity['id']}/deprecate").status_code == 200
    dropped = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert dropped.status_code == 201, dropped.text
    job = get_job_store().get(dropped.json()["job"]["id"])
    assert job is not None
    assert job.status == "succeeded"
    assert job.result["schema"] == "entity_table_drop.v1"
    assert any("DROP TABLE" in stmt for stmt in port.statements)

    already = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert already.status_code == 200
    assert already.json()["job"] is None


