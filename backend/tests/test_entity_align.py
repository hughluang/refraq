def test_publish_creates_table_and_locks(
    client: TestClient, port: RecordingEntityTablePort
) -> None:
    entity = _create(client)
    version_id = entity["current_version"]["id"]
    published = _publish(client, entity)
    job = published["job"]
    assert job["kind"] == "entity_reconcile"
    assert job["status"] == "succeeded"
    assert job["result"]["schema"] == "entity_reconcile.v1"
    assert job["result"]["action"] == "created"
    assert job["result"]["columns_added"] == 1
    assert job["result"]["unique_added"] == 1
    create_sql = port.statements[0]
    assert "CREATE TABLE" in create_sql
    assert '"public"."material"' in create_sql
    assert '"row_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in create_sql
    assert "UNIQUE" in create_sql

    detail = client.get(f"/entities/{entity['id']}/versions/{version_id}")
    version = detail.json()["version"]
    assert version["publish_status"] == "published"
    assert version["table_name"] == "material"
    alignment = version["alignment"]
    assert alignment["table_present"] is True
    assert alignment["definition_ahead"] is False
    assert alignment["latest_job_id"] == job["id"]
    assert alignment["latest_job_status"] == "succeeded"

    events, _ = get_audit_store().list_events(action="entity.publish_enqueue")
    assert events

    second = client.post(f"/entities/{entity['id']}/versions/{version_id}/publish")
    assert second.status_code == 422
    assert second.json()["code"] == "ENTITY_NOT_UNPUBLISHED"


def test_publish_successor_renames_live_table(
    client: TestClient, port: RecordingEntityTablePort
) -> None:
    entity = _create(client)
    v1 = entity["current_version"]["id"]
    _publish(client, entity)
    opened = client.post(f"/entities/{entity['id']}/versions", json={})
    assert opened.status_code == 201
    v2 = opened.json()["version"]["id"]
    live = client.get(f"/entities/{entity['id']}/versions/{v1}")
    assert live.json()["version"]["table_name"] == "material"
    current = client.get(f"/entities/{entity['id']}").json()["entity"]
    _publish(client, current)
    renamed = client.get(f"/entities/{entity['id']}/versions/{v1}")
    assert renamed.json()["version"]["table_name"] == "material__rfq_v1"
    successor = client.get(f"/entities/{entity['id']}/versions/{v2}")
    assert successor.json()["version"]["table_name"] == "material"
    assert any("RENAME TO" in stmt for stmt in port.statements)
    assert any('"public"."material__rfq_v1"' in stmt for stmt in port.statements)

    dropped = client.post(f"/entities/{entity['id']}/versions/{v1}/drop-table")
    assert dropped.status_code == 201, dropped.text
    job = get_job_store().get(dropped.json()["job"]["id"])
    assert job is not None
    assert job.status == "succeeded"


